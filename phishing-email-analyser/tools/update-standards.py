#!/usr/bin/env python3
"""Explicit, online-only refresh of Unicode confusables and the official PSL.

Sources: Unicode Security 18.0.0 (UTS #39) and publicsuffix.org.
This downloads reference data only; the shipped browser application is offline.
Generated Unicode substitution data is one component of UTS #39 and does NOT
claim entire standard conformance (case-folding and identifier status matter).
"""
import datetime
import hashlib
import json
from pathlib import Path
import re
import urllib.request

ROOT = Path(__file__).resolve().parents[1]
SOURCES = {
    'confusables': 'https://www.unicode.org/Public/18.0.0/security/confusables.txt',
    'psl': 'https://publicsuffix.org/list/public_suffix_list.dat',
}

def download(url):
    req=urllib.request.Request(url, headers={'User-Agent':'CyberstepsCourseDataUpdate/1.0'})
    with urllib.request.urlopen(req, timeout=35) as res:
        value=res.read(3_000_000+1)
    if len(value)>3_000_000:raise ValueError('Reference data exceeds 3MB limit')
    return value

def write_js(filename, attribute, value):
    output='/* Generated by tools/update-standards.py. See ../README.md. */\n'
    output+='(function(r){"use strict";(r.PEA||(r.PEA={})).'+attribute+'='+json.dumps(value, ensure_ascii=False,separators=(',',':'))+';})(typeof window!=="undefined"?window:globalThis);\n'
    (ROOT/'js'/filename).write_text(output,encoding='utf-8')

def main():
    raw={key:download(url) for key,url in SOURCES.items()}
    data=raw['confusables'].decode('utf8');mappings={}
    for line in data.splitlines():
        if line.startswith('#') or not line.strip():continue
        parts=[v.strip() for v in line.split('#',1)[0].split(';')]
        if len(parts)<2:continue
        source=[int(v,16) for v in parts[0].split()]
        target=''.join(chr(int(v,16)) for v in parts[1].split())
        if len(source)==1 and target:
            mappings[chr(source[0])]=target
    if len(mappings)<500:raise ValueError('Unicode data sanity check failed')
    psl=[]
    for line in raw['psl'].decode('utf8').splitlines():
        line=line.strip().lower()
        if not line or line.startswith('//'):continue
        psl.append(line)
    if len(psl)<3000:raise ValueError('PSL sanity check failed')
    write_js('confusables-data.js','confusableMappings',dict(sorted(mappings.items())))
    write_js('psl-data.js','pslRules',sorted(set(psl)))
    metadata={'updated_at':datetime.datetime.now(datetime.timezone.utc).isoformat(),
              'source':SOURCES,'sha256':{k:hashlib.sha256(v).hexdigest() for k,v in raw.items()},
              'mappings':len(mappings),'psl_rules':len(set(psl)),
              'caveat':'Data-derived skeleton matching, not full UTS #39 conformance'}
    (ROOT/'data').mkdir(parents=True, exist_ok=True)
    (ROOT/'data'/'standards-manifest.json').write_text(json.dumps(metadata,indent=2)+'\n')
    print(json.dumps(metadata,indent=2))

if __name__=='__main__':main()
